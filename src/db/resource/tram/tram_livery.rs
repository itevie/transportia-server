use crate::db::resource::tram::tram_livery_def::TramLivery;
use sqlx::PgPool;

pub static SQL_TRAM_LIVERY: &str = r#"
CREATE TABLE IF NOT EXISTS tram_livery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    css TEXT,
    text_colour TEXT
)
"#;

#[derive(Clone)]
pub struct TramLiveries {
    pool: PgPool,
}

impl TramLiveries {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<TramLivery>> {
        sqlx::query_as::<_, TramLivery>(
            r#"
            SELECT id, name, css, text_colour
            FROM tram_livery
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &str) -> sqlx::Result<Vec<TramLivery>> {
        let search = format!("%{}%", query);

        sqlx::query_as::<_, TramLivery>(
            r#"
            SELECT id, name, css, text_colour
            FROM tram_livery
            WHERE
                name ILIKE $1
                OR css ILIKE $1
                OR text_colour ILIKE $1
            ORDER BY name
            LIMIT 50
            "#,
        )
        .bind(search)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(&self, livery: &TramLivery) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO tram_livery (
                name,
                css,
                text_colour
            )
            VALUES ($1, $2, $3)
            RETURNING id
            "#,
        )
        .bind(&livery.name)
        .bind(&livery.css)
        .bind(&livery.text_colour)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, livery: &TramLivery) -> sqlx::Result<()> {
        let updated = sqlx::query(
            r#"
            UPDATE tram_livery
            SET
                name = $1,
                css = $2,
                text_colour = $3
            WHERE id = $4
            "#,
        )
        .bind(&livery.name)
        .bind(&livery.css)
        .bind(&livery.text_colour)
        .bind(livery.id)
        .execute(&self.pool)
        .await?;

        if updated.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM tram_livery WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}
