use crate::db::resource::favourite::favourite_group_def::FavouritesGroup;
use serde::Deserialize;
use sqlx::{PgPool, Postgres, QueryBuilder};
use utoipa::{IntoParams, ToSchema};

pub static SQL_FAVOURITES_GROUPS: &str = r#"
CREATE TABLE IF NOT EXISTS favourites_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    favourite_type INTEGER NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    name TEXT NOT NULL,
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct FavouriteGroups {
    pool: PgPool,
}

#[derive(Deserialize, ToSchema, IntoParams)]
pub struct FavouriteGroupQuery {
    pub favourite_type: Option<i64>,
    pub search: Option<String>,
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

impl FavouriteGroups {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<FavouritesGroup>> {
        sqlx::query_as::<_, FavouritesGroup>(
            r#"
            SELECT *
            FROM favourites_groups
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(
        &self,
        query: &FavouriteGroupQuery,
        owner_id: i64,
    ) -> sqlx::Result<Vec<FavouritesGroup>> {
        let page_length = query.page_length.unwrap_or(50).clamp(1, 1000);

        let offset = query.offset.unwrap_or(0).max(0);

        let mut builder =
            QueryBuilder::<Postgres>::new("SELECT * FROM favourites_groups WHERE owner_id = ");

        builder.push_bind(owner_id);

        if let Some(favourite_type) = query.favourite_type {
            builder
                .push(" AND favourite_type = ")
                .push_bind(favourite_type);
        }

        if let Some(search) = &query.search {
            builder
                .push(" AND name ILIKE ")
                .push_bind(format!("%{search}%"));
        }

        builder
            .push(" ORDER BY name LIMIT ")
            .push_bind(page_length)
            .push(" OFFSET ")
            .push_bind(offset);

        builder
            .build_query_as::<FavouritesGroup>()
            .fetch_all(&self.pool)
            .await
    }

    pub async fn create(
        &self,
        favourite_type: i64,
        owner_id: i64,
        name: &str,
        created_at: &str,
    ) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO favourites_groups (
                favourite_type,
                owner_id,
                name,
                created_at
            )
            VALUES ($1, $2, $3, $4)
            RETURNING id
            "#,
        )
        .bind(favourite_type)
        .bind(owner_id)
        .bind(name)
        .bind(created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, group: &FavouritesGroup) -> sqlx::Result<bool> {
        let result = sqlx::query(
            r#"
            UPDATE favourites_groups SET
                favourite_type = $1,
                name = $2
            WHERE id = $3
            "#,
        )
        .bind(group.favourite_type)
        .bind(&group.name)
        .bind(group.id)
        .execute(&self.pool)
        .await?;

        Ok(result.rows_affected() > 0)
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<bool> {
        // TODO: Remove this group from favourites before deleting it.

        let result = sqlx::query("DELETE FROM favourites_groups WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(result.rows_affected() > 0)
    }
}
