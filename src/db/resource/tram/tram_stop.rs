use crate::db::resource::tram::tram_stop_def::TramStop;
use sqlx::PgPool;

pub static SQL_TRAM_STOP: &str = r#"
CREATE TABLE IF NOT EXISTS tram_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    operator_id BIGINT REFERENCES tram_operators(id),
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct TramStops {
    pool: PgPool,
}

impl TramStops {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<TramStop>> {
        sqlx::query_as::<_, TramStop>(
            r#"
            SELECT *
            FROM tram_stops
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &str) -> sqlx::Result<Vec<TramStop>> {
        let search = format!("%{}%", query);

        sqlx::query_as::<_, TramStop>(
            r#"
            SELECT *
            FROM tram_stops
            WHERE name ILIKE $1
            ORDER BY name
            LIMIT 50
            "#,
        )
        .bind(search)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(&self, stop: &TramStop) -> sqlx::Result<i64> {
        sqlx::query_scalar(
            r#"
            INSERT INTO tram_stops (
                name,
                operator_id,
                created_at
            )
            VALUES ($1, $2, $3)
            RETURNING id
            "#,
        )
        .bind(&stop.name)
        .bind(stop.operator_id)
        .bind(&stop.created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, stop: &TramStop) -> sqlx::Result<()> {
        let result = sqlx::query(
            r#"
            UPDATE tram_stops
            SET
                name = $1,
                operator_id = $2,
                created_at = $3
            WHERE id = $4
            "#,
        )
        .bind(&stop.name)
        .bind(stop.operator_id)
        .bind(&stop.created_at)
        .bind(stop.id)
        .execute(&self.pool)
        .await?;

        if result.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM tram_stops WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}
