    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM model_buses WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        model_buses: Vec<ModelBus>,
        user_id: Option<i64>,
    ) -> sqlx::Result<Vec<ModelBusFilledOut>> {
        let mut filled_out = Vec::with_capacity(model_buses.len());

        for model_bus in model_buses {
            let operator = match &model_bus.operator_link {
                Some(id) => db.tx_operators.get(id).await?,
                None => None,
            };

            let livery = match model_bus.livery_link {
                Some(id) => db.liveries.get(id).await?,
                None => None,
            };

            let vehicle = match model_bus.vehicle_link {
                Some(id) => db.vehicles.get(id).await?,
                None => None,
            };

            let vehicle_type = match model_bus.vehicle_type_link {
                Some(id) => db.vehicle_types.get(id).await?,
                None => None,
            };

            let route = match &model_bus.route_link {
                Some(id) => db.tx_lines.get(id).await?,
                None => None,
            };

            let photos = db
                .photos
                .search_new(&PhotoQuery {
                    id: None,
                    author_id: None,
                    photo_type: Some(PhotoType::ModelBus),
                    title: None,
                    description: None,
                    search: None,
                    bd_reg: None,
                    bd_fleet: None,
                    bd_livery_id: None,
                    bd_vehicle_type_id: None,
                    bd_vehicle_id: None,
                    bd_has_matched_vehicle: None,
                    bd_route: None,
                    bd_operator_id: None,
                    td_fleet: None,
                    td_livery_id: None,
                    td_vehicle_type_id: None,
                    td_operator_id: None,
                    td_vehicle_id: None,
                    td_has_matched_vehicle: None,
                    mbd_manufacturer: None,
                    mbd_product_code: None,
                    mbd_scale: None,
                    mbd_operator: None,
                    mbd_livery: None,
                    mbd_fleet_number: None,
                    mbd_registration: None,
                    mbd_route_number: None,
                    mbd_destination: None,
                    mbd_vehicle_type: None,
                    mbd_has_certificate: None,
                    mbd_released: None,
                    mbd_model_id: Some(model_bus.id),
                    mbd_has_matched_model: None,
                    mbd_owner_id: None,
                    page_length: None,
                    offset: None,
                    order_by: None,
                })
                .await?;

            let photo = photos.items.into_iter().next();

            filled_out.push(ModelBusFilledOut {
                id: model_bus.id,
                product_code: model_bus.product_code,
                manufacturer: model_bus.manufacturer,
                scale: model_bus.scale,
                operator: model_bus.operator,
                operator_link: model_bus.operator_link,
                operator_obj: operator,
                livery: model_bus.livery,
                livery_link: model_bus.livery_link,
                livery_obj: livery,
                fleet_number: model_bus.fleet_number,
                registration: model_bus.registration,
                vehicle_link: model_bus.vehicle_link,
                vehicle_obj: vehicle,
                route_number: model_bus.route_number,
                destination: model_bus.destination,
                route_link: model_bus.route_link,
                route_obj: route,
                vehicle_type: model_bus.vehicle_type,
                vehicle_type_link: model_bus.vehicle_type_link,
                vehicle_type_obj: vehicle_type,
                has_certificate: model_bus.has_certificate,
                certificate_max: model_bus.certificate_max,
                released: model_bus.released,
                photo,
                created_at: model_bus.created_at,
                updated_at: model_bus.updated_at,
            });
        }

        Ok(filled_out)
    }
