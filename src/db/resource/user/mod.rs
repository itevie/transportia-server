pub mod def;

use crate::db::resource::user::def::User;
use serde::Deserialize;
use sqlx::{PgPool, Postgres, QueryBuilder};
use utoipa::{IntoParams, ToSchema};

pub static SQL_USER: &str = r#"
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT,
    bio TEXT,
    password_hash TEXT NOT NULL,
    public_favourites BOOLEAN NOT NULL DEFAULT FALSE,
    trusted_user BOOLEAN NOT NULL DEFAULT FALSE,
    admin BOOLEAN NOT NULL DEFAULT FALSE
)
"#;

#[derive(Clone)]
pub struct Users {
    pool: PgPool,
}

#[derive(Deserialize, ToSchema, IntoParams)]
pub struct UserQuery {
    pub search: Option<String>,
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

impl Users {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64, include_sensitive: bool) -> sqlx::Result<Option<User>> {
        sqlx::query_as::<_, User>(
            r#"
            SELECT
                id,
                CASE WHEN $2 THEN email ELSE ''::TEXT END AS email,
                username,
                display_name,
                bio,
                trusted_user,
                public_favourites,
                admin,
                ''::TEXT AS password_hash
            FROM users
            WHERE id = $1
            "#,
        )
        .bind(id)
        .bind(include_sensitive)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn get_by_username(&self, username: &str) -> sqlx::Result<Option<User>> {
        sqlx::query_as::<_, User>(
            r#"
            SELECT
                id,
                ''::TEXT AS email,
                username,
                display_name,
                bio,
                trusted_user,
                public_favourites,
                admin,
                ''::TEXT AS password_hash
            FROM users
            WHERE username = $1
            "#,
        )
        .bind(username.to_lowercase())
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn get_by_email(
        &self,
        email: &str,
        include_sensitive: bool,
    ) -> sqlx::Result<Option<User>> {
        sqlx::query_as::<_, User>(
            r#"
            SELECT
                id,
                CASE WHEN $2 THEN email ELSE ''::TEXT END AS email,
                username,
                display_name,
                bio,
                trusted_user,
                public_favourites,
                admin,
                CASE WHEN $2 THEN password_hash ELSE ''::TEXT END AS password_hash
            FROM users
            WHERE email = $1
            "#, 
        )
        .bind(email.to_lowercase())
        .bind(include_sensitive)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &UserQuery) -> sqlx::Result<Vec<User>> {
        let page_length = query.page_length.map(|x| x.min(1000)).unwrap_or(50);

        let mut builder = QueryBuilder::<Postgres>::new(
            r#"
            SELECT
                id,
                ''::TEXT AS email,
                username,
                display_name,
                bio,
                trusted_user,
                public_favourites,
                admin,
                ''::TEXT AS password_hash
            FROM users
            WHERE TRUE
            "#,
        );

        if let Some(value) = query.search.as_deref() {
            let pattern = format!("%{}%", value);

            builder
                .push(" AND (username ILIKE ")
                .push_bind(pattern.clone())
                .push(" OR display_name ILIKE ")
                .push_bind(pattern)
                .push(")");
        }

        builder.push(" ORDER BY username");

        builder.push(" LIMIT ").push_bind(page_length);

        if let Some(offset) = query.offset {
            builder.push(" OFFSET ").push_bind(offset);
        }

        builder.build_query_as::<User>().fetch_all(&self.pool).await
    }

    pub async fn create(&self, email: &str, username: &str, password: &str) -> sqlx::Result<i64> {
        let password_hash = bcrypt::hash(password, bcrypt::DEFAULT_COST)
            .map_err(|err| sqlx::Error::Protocol(err.to_string()))?;

        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO users (
                email,
                username,
                password_hash
            )
            VALUES ($1, $2, $3)
            RETURNING id
            "#,
        )
        .bind(email)
        .bind(username)
        .bind(password_hash)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, user: &User) -> sqlx::Result<()> {
        sqlx::query(
            r#"
                UPDATE users SET
                    username = $1,
                    display_name = $2,
                    bio = $3,
                    trusted_user = $4,
                    admin = $5,
                    public_favourites = $6
                WHERE id = $7
                "#,
            )
            .bind(&user.username)
            .bind(&user.display_name)
            .bind(&user.bio)
            .bind(user.trusted_user)
            .bind(user.admin)
            .bind(user.public_favourites)
            .bind(user.id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM users WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn check_password(&self, email: &str, password: &str) -> sqlx::Result<Option<User>> {
        let Some(mut user) = self.get_by_email(email, true).await? else {
            return Ok(None);
        };

        let valid = bcrypt::verify(password, &user.password_hash)
            .map_err(|err| sqlx::Error::Protocol(err.to_string()))?;

        if !valid {
            return Ok(None);
        }

        user.password_hash.clear();

        Ok(Some(user))
    }
}
