use std::sync::Arc;

use sqlx::PgPool;

use crate::db::Database;
use crate::db::resource::checklist::checklist_item_def::{
    RouteChecklistItem, RouteChecklistItemFilledOut,
};

pub static SQL_ROUTE_CHECKLIST_ITEMS: &str = r#"
CREATE TABLE IF NOT EXISTS route_checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id BIGINT NOT NULL REFERENCES route_checklists(id),
    line_id TEXT NOT NULL REFERENCES tx_lines(tx_id),
    added_at TEXT NOT NULL,
    completed_at TEXT,

    UNIQUE(checklist_id, line_id)
)
"#;

#[derive(Clone)]
pub struct RouteChecklistItems {
    pool: PgPool,
}

impl RouteChecklistItems {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<RouteChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklistItem>(
            r#"
            SELECT *
            FROM route_checklist_items
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn get_by_checklist(
        &self,
        checklist_id: i64,
    ) -> Result<Vec<RouteChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklistItem>(
            r#"
            SELECT *
            FROM route_checklist_items
            WHERE checklist_id = $1
            ORDER BY added_at ASC
            "#,
        )
        .bind(checklist_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn get_by_line(
        &self,
        checklist_id: i64,
        line_id: &str,
    ) -> Result<Option<RouteChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklistItem>(
            r#"
            SELECT *
            FROM route_checklist_items
            WHERE checklist_id = $1
              AND line_id = $2
            "#,
        )
        .bind(checklist_id)
        .bind(line_id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn create(
        &self,
        checklist_id: i64,
        line_id: &str,
        added_at: &str,
    ) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            INSERT INTO route_checklist_items (
                checklist_id,
                line_id,
                added_at
            )
            VALUES ($1, $2, $3)
            ON CONFLICT (checklist_id, line_id) DO NOTHING
            RETURNING id
            "#,
        )
        .bind(checklist_id)
        .bind(line_id)
        .bind(added_at)
        .fetch_optional(&self.pool)
        .await?
        .map_or_else(|| Err(sqlx::Error::RowNotFound), Ok)
    }

    pub async fn update(&self, item: &RouteChecklistItem) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE route_checklist_items
            SET
                checklist_id = $1,
                line_id = $2,
                added_at = $3,
                completed_at = $4
            WHERE id = $5
            "#,
        )
        .bind(item.checklist_id)
        .bind(&item.line_id)
        .bind(&item.added_at)
        .bind(&item.completed_at)
        .bind(item.id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn set_completed(
        &self,
        id: i64,
        completed_at: Option<&str>,
    ) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE route_checklist_items
            SET completed_at = $1
            WHERE id = $2
            "#,
        )
        .bind(completed_at)
        .bind(id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM route_checklist_items WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        items: Vec<RouteChecklistItem>,
    ) -> Result<Vec<RouteChecklistItemFilledOut>, sqlx::Error> {
        let mut filled_out = Vec::with_capacity(items.len());

        for item in items {
            let tx_line = db.tx_lines.get_by_line_id(&item.line_id).await?;

            filled_out.push(RouteChecklistItemFilledOut {
                id: item.id,
                checklist_id: item.checklist_id,
                line_id: item.line_id,
                line: tx_line.unwrap_or_default(),
                added_at: item.added_at,
                completed_at: item.completed_at,
            });
        }

        Ok(filled_out)
    }
}
