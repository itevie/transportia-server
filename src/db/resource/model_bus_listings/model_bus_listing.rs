    pub async fn fetch(
        &self,
    ) -> Result<Vec<BusListingResource>, sqlx::Error> {
        sqlx::query_as::<_, BusListingResource>(
            "SELECT * FROM bus_listings",
        )
            .fetch_all(&self.pool)
            .await
    }

    pub async fn search(
        &self,
        query: &BusListingQuery,
    ) -> Result<Vec<BusListingResource>, sqlx::Error> {
        let page_length = query.page_length.unwrap_or(50).min(1000);

        let mut builder = QueryBuilder::<Postgres>::new(
            "SELECT * FROM bus_listings WHERE 1 = 1",
        );

        filter_ilike!(
            builder,
            "scale",
            query.scale.as_deref()
        );

        filter_ilike!(
            builder,
            "origin_code",
            query.origin.as_deref()
        );

        filter_ilike!(
            builder,
            "title",
            query.title.as_deref()
        );
        

        filter_ilike!(
            builder,
            "manufacturer",
            query.manufacturer.as_deref()
        );

        filter_ilike!(
            builder,
            "manufacturer_code",
            query.manufacturer_code.as_deref()
        );

        filter_ilike!(
            builder,
            "condition",
            query.condition.as_deref()
        );

        filter_ilike!(
            builder,
            "category",
            query.category.as_deref()
        );

        if let Some(value) = &query.price_low {
            if let Ok(value) = value.parse::<f64>() {
                builder
                    .push(" AND price_low >= ")
                    .push_bind(value);
            }
        }

        if let Some(value) = &query.price_high {
            if let Ok(value) = value.parse::<f64>() {
                builder
                    .push(" AND price_high <= ")
                    .push_bind(value);
            }
        }

        filter_search!(
            builder,
            query.search.as_deref(),
            [
                "title",
                "description",
                "manufacturer",
                "manufacturer_code",
                "scale",
                "origin",
                "origin_code",
                "condition",
                "category",
                "seller_name"
            ]
        );

        match query.sort.as_deref() {
            Some("price-low-high") => {
                builder.push(" ORDER BY price_low ASC");
            }
            Some("price-high-low") => {
                builder.push(" ORDER BY price_low DESC");
            }
            _ => {}
        }

        builder
            .push(" LIMIT ")
            .push_bind(page_length);

        if let Some(offset) = query.offset {
            builder
                .push(" OFFSET ")
                .push_bind(offset);
        }

        builder
            .build_query_as::<BusListingResource>()
            .fetch_all(&self.pool)
            .await
    }

    pub async fn get_query_options(
        &self,
    ) -> Result<BusListingQueryOptions, sqlx::Error> {
        let scale = sqlx::query_scalar::<_, String>(
            r#"
            SELECT DISTINCT scale
            FROM bus_listings
            WHERE scale IS NOT NULL AND scale != ''
            ORDER BY scale
            "#,
        )
            .fetch_all(&self.pool)
            .await?;

        let origin_code = sqlx::query_scalar::<_, String>(
            r#"
            SELECT DISTINCT origin_code
            FROM bus_listings
            WHERE origin_code IS NOT NULL AND origin_code != ''
            ORDER BY origin_code
            "#,
        )
            .fetch_all(&self.pool)
            .await?;

        let manufacturer = sqlx::query_scalar::<_, String>(
            r#"
            SELECT DISTINCT manufacturer
            FROM bus_listings
            WHERE manufacturer IS NOT NULL AND manufacturer != ''
            ORDER BY manufacturer
            "#,
        )
            .fetch_all(&self.pool)
            .await?;

        let manufacturer_code = sqlx::query_scalar::<_, String>(
            r#"
            SELECT DISTINCT manufacturer_code
            FROM bus_listings
            WHERE manufacturer_code IS NOT NULL
              AND manufacturer_code != ''
            ORDER BY manufacturer_code
            "#,
        )
            .fetch_all(&self.pool)
            .await?;

        let condition = sqlx::query_scalar::<_, String>(
            r#"
            SELECT DISTINCT condition
            FROM bus_listings
            WHERE condition IS NOT NULL AND condition != ''
            ORDER BY condition
            "#,
        )
            .fetch_all(&self.pool)
            .await?;

        Ok(BusListingQueryOptions {
            scale,
            origin_code,
            manufacturer,
            manufacturer_code,
            condition,
        })
    }

