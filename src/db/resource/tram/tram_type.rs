use crate::db::resource::tram::tram_type_def::TramType;
use sqlx::{PgPool, query_as, query_scalar};

pub static SQL_TRAM_TYPE: &str = r#"
CREATE TABLE IF NOT EXISTS tram_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct TramTypes {
    pool: PgPool,
}

impl TramTypes {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<TramType>, sqlx::Error> {
        query_as::<_, TramType>(
            r#"
            SELECT *
            FROM tram_type
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &str) -> Result<Vec<TramType>, sqlx::Error> {
        let search = format!("%{}%", query);

        query_as::<_, TramType>(
            r#"
            SELECT *
            FROM tram_type
            WHERE name ILIKE $1
            ORDER BY name
            LIMIT 50
            "#,
        )
        .bind(search)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(&self, tram_type: &TramType) -> Result<i64, sqlx::Error> {
        query_scalar(
            r#"
            INSERT INTO tram_type (name)
            VALUES ($1)
            RETURNING id
            "#,
        )
        .bind(&tram_type.name)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, tram_type: &TramType) -> Result<(), sqlx::Error> {
        let updated = sqlx::query(
            r#"
            UPDATE tram_type
            SET name = $1
            WHERE id = $2
            "#,
        )
        .bind(&tram_type.name)
        .bind(tram_type.id)
        .execute(&self.pool)
        .await?;

        if updated.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM tram_type WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}
