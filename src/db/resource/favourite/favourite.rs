use std::sync::Arc;

use chrono::Utc;
use sqlx::{
    Decode, PgPool, Postgres, Type,
    postgres::{PgTypeInfo, PgValueRef},
};

use crate::db::Database;
use crate::db::resource::bustimes::vehicle::BtVehicles;
use crate::db::resource::comment::comment::Comments;
use crate::db::resource::favourite::favourite_def::{
    Favourite, FavouriteFilled, FavouriteObject, FavouriteType,
};
use crate::db::resource::model_bus::model_bus::ModelBuses;
use crate::db::resource::photo::photo::Photos;
use crate::db::resource::tram::tram::Trams;

pub static SQL_FAVOURITE: &str = r#"
CREATE TABLE IF NOT EXISTS favourites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    target_id TEXT NOT NULL,
    target_type INTEGER NOT NULL,
    group_id BIGINT REFERENCES favourites_groups(id),
    created_at TEXT NOT NULL,

    UNIQUE(user_id, target_id, target_type)
)
"#;

#[derive(Clone)]
pub struct Favourites {
    pool: PgPool,
}

impl Favourites {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get_by_type(
        &self,
        user_id: i64,
        target_type: FavouriteType,
    ) -> sqlx::Result<Vec<Favourite>> {
        sqlx::query_as::<_, Favourite>(
            r#"
            SELECT
                id,
                user_id,
                target_id,
                target_type,
                created_at,
                group_id
            FROM favourites
            WHERE user_id = $1
              AND target_type = $2
            ORDER BY created_at DESC
            "#,
        )
        .bind(user_id)
        .bind(target_type)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn get(
        &self,
        user_id: i64,
        target_type: FavouriteType,
        target_id: i64,
    ) -> sqlx::Result<Option<Favourite>> {
        sqlx::query_as::<_, Favourite>(
            r#"
            SELECT
                id,
                user_id,
                target_id,
                target_type,
                created_at,
                group_id
            FROM favourites
            WHERE user_id = $1
              AND target_type = $2
              AND target_id = $3
            ORDER BY created_at DESC
            LIMIT 1
            "#,
        )
        .bind(user_id)
        .bind(target_type)
        .bind(target_id.to_string())
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn create(
        &self,
        user_id: i64,
        target_id: i64,
        target_type: FavouriteType,
    ) -> sqlx::Result<i64> {
        let created_at = Utc::now().to_rfc3339();

        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO favourites (
                user_id,
                target_id,
                target_type,
                created_at
            )
            VALUES ($1, $2, $3, $4)
            ON CONFLICT (user_id, target_id, target_type)
            DO UPDATE SET target_id = EXCLUDED.target_id
            RETURNING id
            "#,
        )
        .bind(user_id)
        .bind(target_id.to_string())
        .bind(target_type)
        .bind(created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn get_by_group_id(
        &self,
        user_id: i64,
        group_id: i64,
    ) -> sqlx::Result<Vec<Favourite>> {
        sqlx::query_as::<_, Favourite>(
            r#"
            SELECT
                id,
                user_id,
                target_id,
                target_type,
                created_at,
                group_id
            FROM favourites
            WHERE user_id = $1
              AND group_id = $2
            ORDER BY created_at DESC
            "#,
        )
        .bind(user_id)
        .bind(group_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn update_group_id(
        &self,
        user_id: i64,
        target_id: i64,
        target_type: FavouriteType,
        group_id: Option<i64>,
    ) -> sqlx::Result<bool> {
        let result = sqlx::query(
            r#"
            UPDATE favourites
            SET group_id = $1
            WHERE user_id = $2
              AND target_id = $3
              AND target_type = $4
            "#,
        )
        .bind(group_id)
        .bind(user_id)
        .bind(target_id.to_string())
        .bind(target_type)
        .execute(&self.pool)
        .await?;

        Ok(result.rows_affected() > 0)
    }

    pub async fn delete(
        &self,
        user_id: i64,
        target_id: i64,
        target_type: FavouriteType,
    ) -> sqlx::Result<()> {
        sqlx::query(
            r#"
            DELETE FROM favourites
            WHERE user_id = $1
              AND target_id = $2
              AND target_type = $3
            "#,
        )
        .bind(user_id)
        .bind(target_id.to_string())
        .bind(target_type)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn fill(
        &self,
        db: Arc<Database>,
        favourites: Vec<Favourite>,
        user_id: Option<i64>,
    ) -> sqlx::Result<Vec<FavouriteFilled>> {
        let mut filled = Vec::with_capacity(favourites.len());

        for favourite in favourites {
            let target_id = favourite
                .target_id
                .parse::<i64>()
                .map_err(|err| sqlx::Error::Decode(Box::new(err)))?;

            let object = match favourite.target_type {
                FavouriteType::Photo => {
                    let photo = db
                        .photos
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    let mut result = Photos::fill_out(db.clone(), vec![photo], user_id).await?;

                    FavouriteObject::BusPhoto(result.pop().ok_or(sqlx::Error::RowNotFound)?)
                }

                FavouriteType::Comment => {
                    let comment = db
                        .comments
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    let filled_out = Comments::fill_out(db.clone(), comment, user_id).await?;

                    FavouriteObject::Comment(filled_out)
                }

                FavouriteType::Tram => {
                    let tram = db
                        .trams
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    let mut result = Trams::fill_out(db.clone(), vec![tram], user_id).await?;

                    FavouriteObject::Tram(result.pop().ok_or(sqlx::Error::RowNotFound)?)
                }

                FavouriteType::ModelBus => {
                    let model_bus = db
                        .model_buses
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    let mut result =
                        ModelBuses::fill_out(db.clone(), vec![model_bus], user_id).await?;

                    FavouriteObject::ModelBus(result.pop().ok_or(sqlx::Error::RowNotFound)?)
                }

                FavouriteType::Operator => {
                    let operator = db
                        .tx_operators
                        .get(&favourite.target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    FavouriteObject::Operator(operator)
                }

                FavouriteType::Vehicle => {
                    let vehicle = db
                        .vehicles
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    let mut result =
                        BtVehicles::fill_out(db.clone(), vec![vehicle], user_id).await?;

                    FavouriteObject::Vehicle(result.pop().ok_or(sqlx::Error::RowNotFound)?)
                }

                FavouriteType::VehicleType => {
                    let vehicle_type = db
                        .vehicle_types
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    FavouriteObject::VehicleType(vehicle_type)
                }

                FavouriteType::Livery => {
                    let livery = db
                        .liveries
                        .get(target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    FavouriteObject::Livery(livery)
                }

                FavouriteType::Service => {
                    let service = db
                        .tx_lines
                        .get(&favourite.target_id)
                        .await?
                        .ok_or(sqlx::Error::RowNotFound)?;

                    FavouriteObject::Service(service)
                }
            };

            filled.push(FavouriteFilled {
                id: favourite.id,
                user_id: favourite.user_id,
                target_id: favourite.target_id,
                target_type: favourite.target_type,
                created_at: favourite.created_at,
                object,
                group: favourite.group,
            });
        }

        Ok(filled)
    }
}
