use sqlx::{PgPool, Row};
use crate::db::resource::star_rating::star_rating_def::PhotoRating;

pub static SQL_PHOTO_RATING: &str = r#"
CREATE TABLE IF NOT EXISTS photo_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct PhotoRatings {
    pool: PgPool,
}

impl PhotoRatings {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<PhotoRating>, sqlx::Error> {
        sqlx::query_as::<_, PhotoRating>(
            r#"
            SELECT *
            FROM photo_ratings
            WHERE id = $1
            "#,
        )
            .bind(id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn get_by_photo_id(
        &self,
        photo_id: i64,
    ) -> Result<Vec<PhotoRating>, sqlx::Error> {
        sqlx::query_as::<_, PhotoRating>(
            r#"
            SELECT *
            FROM photo_ratings
            WHERE photo_id = $1
            ORDER BY created_at DESC
            "#,
        )
            .bind(photo_id)
            .fetch_all(&self.pool)
            .await
    }

    pub async fn get_by_user_and_photo(
        &self,
        user_id: i64,
        photo_id: i64,
    ) -> Result<Option<PhotoRating>, sqlx::Error> {
        sqlx::query_as::<_, PhotoRating>(
            r#"
            SELECT *
            FROM photo_ratings
            WHERE user_id = $1
              AND photo_id = $2
            "#,
        )
            .bind(user_id)
            .bind(photo_id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn average_rating(
        &self,
        photo_id: i64,
    ) -> Result<f64, sqlx::Error> {
        let average: f64 = sqlx::query_scalar(
            r#"
            SELECT COALESCE(AVG(rating), 0.0)::DOUBLE PRECISION
            FROM photo_ratings
            WHERE photo_id = $1
            "#,
        )
            .bind(photo_id)
            .fetch_one(&self.pool)
            .await?;

        Ok(average)
    }

    pub async fn create(
        &self,
        rating: &PhotoRating,
    ) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            INSERT INTO photo_ratings (
                photo_id,
                user_id,
                rating,
                created_at
            )
            VALUES ($1, $2, $3, $4)
            "#,
        )
            .bind(rating.photo_id)
            .bind(rating.user_id)
            .bind(rating.rating)
            .bind(&rating.created_at)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn upsert(
        &self,
        rating: &PhotoRating,
    ) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            INSERT INTO photo_ratings (
                id,
                photo_id,
                user_id,
                rating,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5)
            ON CONFLICT(id) DO UPDATE SET
                photo_id = EXCLUDED.photo_id,
                user_id = EXCLUDED.user_id,
                rating = EXCLUDED.rating,
                created_at = EXCLUDED.created_at
            "#,
        )
            .bind(rating.id)
            .bind(rating.photo_id)
            .bind(rating.user_id)
            .bind(rating.rating)
            .bind(&rating.created_at)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query(
            "DELETE FROM photo_ratings WHERE id = $1",
        )
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn delete_by_user_and_photo(
        &self,
        user_id: i64,
        photo_id: i64,
    ) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            DELETE FROM photo_ratings
            WHERE user_id = $1
              AND photo_id = $2
            "#,
        )
            .bind(user_id)
            .bind(photo_id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}