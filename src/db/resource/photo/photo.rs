    pub async fn patch(&self, id: i64, update: &PhotoUpdate) -> sqlx::Result<()> {
        let mut builder = QueryBuilder::<Postgres>::new("UPDATE photos SET ");
        let mut separated = builder.separated(", ");
        let mut has_fields = false;

        if let Some(value) = &update.title {
            separated.push("title = ").push_bind_unseparated(value);
            has_fields = true;
        }

        if let Some(value) = &update.description {
            separated
                .push("description = ")
                .push_bind_unseparated(value);
            has_fields = true;
        }

        if !has_fields {
            return Ok(());
        }

        builder.push(" WHERE id = ").push_bind(id);

        builder.build().execute(&self.pool).await?;

        Ok(())
    }

    pub async fn delete(&self, db: Arc<Database>, id: i64, user_id: i64) -> sqlx::Result<()> {
        let photo = db.photos.get(id).await?.ok_or(sqlx::Error::RowNotFound)?;

        sqlx::query("DELETE FROM photos WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        db.favourites
            .delete(user_id, id, FavouriteType::Photo)
            .await?;

        if let Some(comment_thread) = photo.comment_thread {
            db.comment_threads.delete(comment_thread).await?;
        }

        if let Some(details_id) = photo.obj_details_id {
            if matches!(photo.photo_type, PhotoType::Bus) {
                db.bus_photo_details.delete(details_id).await?;
            }
        }

        Ok(())
    }

    pub async fn get_or_create_comment_thread(&self, photo_id: i64) -> sqlx::Result<i64> {
        let mut tx = self.pool.begin().await?;

        // Lock the photo row so concurrent requests don't create multiple
        // comment threads for the same photo.
        let existing = sqlx::query_scalar::<_, Option<i64>>(
            "SELECT comment_thread FROM photos WHERE id = $1 FOR UPDATE",
        )
        .bind(photo_id)
        .fetch_optional(&mut *tx)
        .await?
        .ok_or(sqlx::Error::RowNotFound)?;

        if let Some(thread_id) = existing {
            tx.commit().await?;
            return Ok(thread_id);
        }

        let now = Utc::now().to_rfc3339();

        let thread_id = sqlx::query_scalar::<_, i64>(
            "INSERT INTO comment_threads (created_at) VALUES ($1) RETURNING id",
        )
        .bind(now)
        .fetch_one(&mut *tx)
        .await?;

        sqlx::query(
            r#"
            UPDATE photos
            SET comment_thread = $1
            WHERE id = $2
            "#,
        )
        .bind(thread_id)
        .bind(photo_id)
        .execute(&mut *tx)
        .await?;

        tx.commit().await?;

        Ok(thread_id)
    }

    pub async fn get_bus_details(
        db: Arc<Database>,
        mut photo: Photo,
    ) -> sqlx::Result<BusPhotoDetails> {
        if !matches!(photo.photo_type, PhotoType::Bus) {
            return Err(sqlx::Error::Protocol(
                "Photo's type is not PhotoType::Bus in get_bus_details".into(),
            ));
        }

        if let Some(id) = photo.obj_details_id {
            return db
                .bus_photo_details
                .get(id)
                .await?
                .ok_or(sqlx::Error::RowNotFound);
        }

        let details_id = db
            .bus_photo_details
            .create(&BusPhotoDetails {
                id: 0,
                matched_vehicle_id: None,
                override_match: false,
                reg: None,
                fleet: None,
                livery_id: None,
                vehicle_type_id: None,
                route_id: None,
            })
            .await?;

        let details = db
            .bus_photo_details
            .get(details_id)
            .await?
            .ok_or(sqlx::Error::RowNotFound)?;

        photo.obj_details_id = Some(details.id);
        db.photos.update(&photo).await?;

        Ok(details)
    }

