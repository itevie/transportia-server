use std::sync::Arc;

use sqlx::PgPool;

use crate::db::Database;
use crate::db::resource::photo::tram_photo_details_def::{
    TramPhotoDetails, TramPhotoDetailsFilledOut, TramPhotoDetailsUpdate,
};
use crate::db::resource::tram::tram::Trams;
use crate::db::resource::tram::tram_def::TramFilledOut;

pub static SQL_TRAM_PHOTO_DETAILS: &str = r#"
CREATE TABLE IF NOT EXISTS tram_photo_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matched_vehicle_id BIGINT REFERENCES trams(id),
    override_match BOOLEAN NOT NULL DEFAULT FALSE,
    fleet TEXT,
    livery_id BIGINT REFERENCES tram_livery(id),
    vehicle_type_id BIGINT REFERENCES tram_type(id),
    operator_id BIGINT REFERENCES tram_operators(id)
);
"#;

#[derive(Clone)]
pub struct TramPhotoDetailsManager {
    pool: PgPool,
}

impl TramPhotoDetailsManager {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<TramPhotoDetails>> {
        sqlx::query_as::<_, TramPhotoDetails>(
            r#"
            SELECT
                id,
                matched_vehicle_id,
                override_match,
                fleet,
                livery_id,
                vehicle_type_id,
                operator_id
            FROM tram_photo_details
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn create(&self, details: &TramPhotoDetails) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO tram_photo_details (
                matched_vehicle_id,
                override_match,
                fleet,
                livery_id,
                vehicle_type_id,
                operator_id
            )
            VALUES ($1, $2, $3, $4, $5, $6)
            RETURNING id
            "#,
        )
        .bind(details.matched_vehicle_id)
        .bind(details.override_match)
        .bind(&details.fleet)
        .bind(details.livery_id)
        .bind(details.vehicle_type_id)
        .bind(details.operator_id)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, id: i64, update: &TramPhotoDetailsUpdate) -> sqlx::Result<()> {
        sqlx::query(
            r#"
            UPDATE tram_photo_details SET
                matched_vehicle_id = $1,
                override_match = $2,
                fleet = $3,
                livery_id = $4,
                vehicle_type_id = $5,
                operator_id = $6
            WHERE id = $7
            "#,
        )
        .bind(update.matched_vehicle_id)
        .bind(update.override_match)
        .bind(&update.fleet)
        .bind(update.livery_id)
        .bind(update.vehicle_type_id)
        .bind(update.operator_id)
        .bind(id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM tram_photo_details WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        details: TramPhotoDetails,
    ) -> sqlx::Result<TramPhotoDetailsFilledOut> {
        let livery = match details.livery_id {
            Some(id) => db.tram_liveries.get(id).await?,
            None => None,
        };

        let vt = match details.vehicle_type_id {
            Some(id) => db.tram_types.get(id).await?,
            None => None,
        };

        let operator = match details.operator_id {
            Some(id) => db.tram_operators.get(id).await?,
            None => None,
        };

        let matched: Option<TramFilledOut> = match details.matched_vehicle_id {
            Some(id) => match db.trams.get(id).await? {
                Some(tram) => Trams::fill_out(db.clone(), vec![tram], None)
                    .await?
                    .into_iter()
                    .next(),
                None => None,
            },
            None => None,
        };

        Ok(TramPhotoDetailsFilledOut {
            id: details.id,
            matched_vehicle_id: details.matched_vehicle_id,
            matched_vehicle: matched,
            override_match: details.override_match,
            fleet: details.fleet,
            livery_id: details.livery_id,
            livery,
            vehicle_type_id: details.vehicle_type_id,
            vehicle_type: vt,
            operator_id: details.operator_id,
            operator,
        })
    }
}
