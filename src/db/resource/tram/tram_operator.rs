use sqlx::PgPool;
use crate::db::resource::tram::tram_operator_def::TramOperator;

pub static SQL_TRAM_OPERATOR: &str = r#"
CREATE TABLE IF NOT EXISTS tram_operators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    website TEXT
)
"#;

#[derive(Clone)]
pub struct TramOperators {
    pool: PgPool,
}

impl TramOperators {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<TramOperator>> {
        sqlx::query_as::<_, TramOperator>(
            r#"
            SELECT id, name, location, website
            FROM tram_operators
            WHERE id = $1
            "#,
        )
            .bind(id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn search(&self, query: &str) -> sqlx::Result<Vec<TramOperator>> {
        let search = format!("%{}%", query);

        sqlx::query_as::<_, TramOperator>(
            r#"
            SELECT id, name, location, website
            FROM tram_operators
            WHERE
                name ILIKE $1
                OR location ILIKE $1
            ORDER BY name
            LIMIT 50
            "#,
        )
            .bind(search)
            .fetch_all(&self.pool)
            .await
    }

    pub async fn create(&self, operator: &TramOperator) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO tram_operators (
                name,
                location,
                website
            )
            VALUES ($1, $2, $3)
            RETURNING id
            "#,
        )
            .bind(&operator.name)
            .bind(&operator.location)
            .bind(&operator.website)
            .fetch_one(&self.pool)
            .await
    }

    pub async fn update(&self, operator: &TramOperator) -> sqlx::Result<()> {
        let updated = sqlx::query(
            r#"
            UPDATE tram_operators
            SET
                name = $1,
                location = $2,
                website = $3
            WHERE id = $4
            "#,
        )
            .bind(&operator.name)
            .bind(&operator.location)
            .bind(&operator.website)
            .bind(operator.id)
            .execute(&self.pool)
            .await?;

        if updated.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM tram_operators WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}