use std::sync::Arc;

use chrono::Utc;
use serde::Deserialize;
use sqlx::{PgPool, Postgres, QueryBuilder};
use utoipa::{IntoParams, ToSchema};

use crate::db::Database;
use crate::db::resource::comment::comment_def::{Comment, CommentFilledOut};
use crate::db::resource::favourite::favourite_def::FavouriteType;

pub static SQL_COMMENT: &str = r#"
CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    body TEXT NOT NULL,
    edited BOOLEAN NOT NULL DEFAULT FALSE,
    edited_at TEXT,
    parent_comment_id BIGINT,
    created_at TEXT NOT NULL,
    FOREIGN KEY (thread) REFERENCES comment_threads(id) ON DELETE CASCADE,
    FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (parent_comment_id) REFERENCES comments(id) ON DELETE CASCADE
)
"#;

#[derive(Clone)]
pub struct Comments {
    pool: PgPool,
}

#[derive(Deserialize, ToSchema, IntoParams)]
pub struct CommentQuery {
    pub thread: Option<i64>,
    pub author_id: Option<i64>,
    pub parent_comment_id: Option<i64>,
    pub search: Option<String>,
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

impl Comments {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<Comment>> {
        sqlx::query_as::<_, Comment>(
            r#"
            SELECT *
            FROM comments
            WHERE id = $1
            "#,
        )
            .bind(id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn get_by_thread(
        &self,
        thread: i64,
    ) -> sqlx::Result<Vec<Comment>> {
        sqlx::query_as::<_, Comment>(
            r#"
            SELECT *
            FROM comments
            WHERE thread = $1
            ORDER BY created_at DESC, id DESC
            "#,
        )
            .bind(thread)
            .fetch_all(&self.pool)
            .await
    }

    pub async fn get_replies(
        &self,
        parent_comment_id: i64,
    ) -> sqlx::Result<Vec<Comment>> {
        sqlx::query_as::<_, Comment>(
            r#"
            SELECT *
            FROM comments
            WHERE parent_comment_id = $1
            ORDER BY created_at ASC, id ASC
            "#,
        )
            .bind(parent_comment_id)
            .fetch_all(&self.pool)
            .await
    }

    pub async fn create(
        &self,
        thread: i64,
        author_id: i64,
        body: &str,
        parent_comment_id: Option<i64>,
    ) -> sqlx::Result<Comment> {
        let created_at = Utc::now().to_rfc3339();

        sqlx::query_as::<_, Comment>(
            r#"
            INSERT INTO comments (
                thread,
                author_id,
                body,
                edited,
                edited_at,
                parent_comment_id,
                created_at
            )
            VALUES ($1, $2, $3, FALSE, NULL, $4, $5)
            RETURNING *
            "#,
        )
            .bind(thread)
            .bind(author_id)
            .bind(body)
            .bind(parent_comment_id)
            .bind(created_at)
            .fetch_one(&self.pool)
            .await
    }

    pub async fn update(&self, comment: &Comment) -> sqlx::Result<()> {
        sqlx::query(
            r#"
            UPDATE comments SET
                body = $1,
                edited = TRUE,
                edited_at = $2
            WHERE id = $3
            "#,
        )
            .bind(&comment.body)
            .bind(Utc::now().to_rfc3339())
            .bind(comment.id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn search(
        &self,
        query: &CommentQuery,
    ) -> sqlx::Result<Vec<Comment>> {
        let page_length = query.page_length.unwrap_or(50).clamp(1, 1000);
        let offset = query.offset.unwrap_or(0).max(0);

        let mut builder = QueryBuilder::<Postgres>::new(
            "SELECT * FROM comments WHERE TRUE",
        );

        if let Some(thread) = query.thread {
            builder
                .push(" AND thread = ")
                .push_bind(thread);
        }

        if let Some(author_id) = query.author_id {
            builder
                .push(" AND author_id = ")
                .push_bind(author_id);
        }

        if let Some(parent_comment_id) = query.parent_comment_id {
            builder
                .push(" AND parent_comment_id = ")
                .push_bind(parent_comment_id);
        }

        if let Some(search) = &query.search {
            builder
                .push(" AND body ILIKE ")
                .push_bind(format!("%{search}%"));
        }

        builder
            .push(" ORDER BY created_at ASC, id ASC LIMIT ")
            .push_bind(page_length)
            .push(" OFFSET ")
            .push_bind(offset);

        builder
            .build_query_as::<Comment>()
            .fetch_all(&self.pool)
            .await
    }

    pub async fn fill_out(
        db: Arc<Database>,
        comment: Comment,
        user_id: Option<i64>,
    ) -> sqlx::Result<CommentFilledOut> {
        let author = db
            .users
            .get(comment.author_id, false)
            .await?
            .ok_or(sqlx::Error::RowNotFound)?;

        let favourite = match user_id {
            Some(user_id) => {
                db.favourites
                    .get(user_id, FavouriteType::Comment, comment.id)
                    .await?
            }
            None => None,
        };

        Ok(CommentFilledOut {
            id: comment.id,
            thread: comment.thread,
            author_id: comment.author_id,
            author,
            body: comment.body,
            edited: comment.edited,
            edited_at: comment.edited_at,
            parent_comment_id: comment.parent_comment_id,
            created_at: comment.created_at,
            is_favourited: user_id.map(|_| favourite.is_some()),
        })
    }

    pub async fn fill_out_many(
        db: Arc<Database>,
        comments: Vec<Comment>,
        user_id: Option<i64>,
    ) -> sqlx::Result<Vec<CommentFilledOut>> {
        let mut filled_out = Vec::with_capacity(comments.len());

        for comment in comments {
            filled_out.push(
                Self::fill_out(db.clone(), comment, user_id).await?,
            );
        }

        Ok(filled_out)
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM comments WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}