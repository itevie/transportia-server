use std::sync::Arc;

use sqlx::PgPool;

use crate::db::Database;
use crate::db::resource::bustimes::vehicle::BtVehicles;
use crate::db::resource::checklist::checklist_def::{Checklist, ChecklistType};
use crate::db::resource::checklist::checklist_item_def::{
    ChecklistItem, ChecklistItemFilledOut, ChecklistObj,
};

pub static SQL_CHECKLIST_ITEMS: &str = r#"
CREATE TABLE IF NOT EXISTS checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id BIGINT NOT NULL REFERENCES checklists(id),
    obj_id TEXT NOT NULL,
    added_at TEXT NOT NULL,
    completed_at TEXT,

    UNIQUE(checklist_id, obj_id)
)
"#;

#[derive(Clone)]
pub struct ChecklistItems {
    pool: PgPool,
}

impl ChecklistItems {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<ChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, ChecklistItem>(
            r#"
            SELECT *
            FROM checklist_items
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn get_by_checklist(
        &self,
        checklist_id: i64,
    ) -> Result<Vec<ChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, ChecklistItem>(
            r#"
            SELECT *
            FROM checklist_items
            WHERE checklist_id = $1
            ORDER BY added_at ASC
            "#,
        )
        .bind(checklist_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn get_by_obj(
        &self,
        checklist_id: i64,
        obj_id: &str,
    ) -> Result<Option<ChecklistItem>, sqlx::Error> {
        sqlx::query_as::<_, ChecklistItem>(
            r#"
            SELECT *
            FROM checklist_items
            WHERE checklist_id = $1
              AND obj_id = $2
            "#,
        )
        .bind(checklist_id)
        .bind(obj_id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn create(
        &self,
        checklist_id: i64,
        obj_id: &str,
        added_at: &str,
    ) -> Result<Option<i64>, sqlx::Error> {
        sqlx::query_scalar(
            r#"
        INSERT INTO checklist_items (
            checklist_id,
            obj_id,
            added_at
        )
        VALUES ($1, $2, $3)
        ON CONFLICT (checklist_id, obj_id) DO NOTHING
        RETURNING id
        "#,
        )
        .bind(checklist_id)
        .bind(obj_id)
        .bind(added_at)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn update(&self, item: &ChecklistItem) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE checklist_items
            SET
                checklist_id = $1,
                obj_id = $2,
                added_at = $3,
                completed_at = $4
            WHERE id = $5
            "#,
        )
        .bind(item.checklist_id)
        .bind(&item.obj_id)
        .bind(&item.added_at)
        .bind(&item.completed_at)
        .bind(item.id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn set_completed(
        &self,
        id: i64,
        completed_at: Option<&str>,
    ) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE checklist_items
            SET completed_at = $1
            WHERE id = $2
            "#,
        )
        .bind(completed_at)
        .bind(id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM checklist_items WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        checklist: Checklist,
        items: Vec<ChecklistItem>,
    ) -> Result<Vec<ChecklistItemFilledOut>, sqlx::Error> {
        let mut filled_out = Vec::with_capacity(items.len());

        for item in items {
            let obj = match checklist.checklist_type {
                ChecklistType::Service => db
                    .tx_lines
                    .get_by_line_id(&item.obj_id)
                    .await?
                    .map(|x| ChecklistObj::Service(x)),
                ChecklistType::Vehicle => {
                    match db
                        .vehicles
                        .get(
                            item.obj_id
                                .parse::<i64>()
                                .map_err(|e| sqlx::Error::Decode(Box::new(e)))?,
                        )
                        .await?
                    {
                        Some(vehicle) => Some(ChecklistObj::Vehicle(
                            BtVehicles::fill_out(db.clone(), vec![vehicle], None)
                                .await?
                                .into_iter()
                                .next()
                                .unwrap(),
                        )),
                        None => None,
                    }
                }
            };

            let Some(obj) = obj else {
                return Err(sqlx::Error::RowNotFound);
            };

            filled_out.push(ChecklistItemFilledOut {
                id: item.id,
                checklist_id: item.checklist_id,
                obj_id: item.obj_id,
                obj,
                added_at: item.added_at,
                completed_at: item.completed_at,
            });
        }

        Ok(filled_out)
    }
}
