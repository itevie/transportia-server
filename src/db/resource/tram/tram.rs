use std::sync::Arc;

use serde::Deserialize;
use sqlx::{FromRow, PgPool, Postgres, QueryBuilder};
use utoipa::{IntoParams, ToSchema};

use crate::db::Database;
use crate::db::resource::favourite::favourite_def::FavouriteType;
use crate::db::resource::photo::photo::PhotoQuery;
use crate::db::resource::photo::photo_def::PhotoType;
use crate::db::resource::tram::tram_def::{Tram, TramFilledOut};

pub static SQL_TRAM: &str = r#"
CREATE TABLE IF NOT EXISTS trams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT REFERENCES tram_operators(id),
    fleet TEXT NOT NULL,
    livery_id BIGINT REFERENCES tram_livery(id),
    tram_type_id BIGINT REFERENCES tram_type(id),
    garage TEXT,
    withdrawn BOOLEAN NOT NULL DEFAULT FALSE,
    name TEXT,
    branding TEXT
);
"#;

#[derive(Debug, Deserialize, ToSchema, IntoParams)]
pub struct TramQuery {
    pub search: Option<String>,

    pub operator: Option<i64>,
    pub fleet: Option<String>,
    pub livery: Option<i64>,
    pub tram_type: Option<i64>,
    pub garage: Option<String>,
    pub withdrawn: Option<bool>,

    pub name: Option<String>,
    pub branding: Option<String>,

    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

#[derive(Clone)]
pub struct Trams {
    pool: PgPool,
}

impl Trams {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<Tram>> {
        sqlx::query_as::<_, Tram>(
            r#"
            SELECT
                id,
                operator_id,
                fleet,
                livery_id,
                tram_type_id,
                garage,
                withdrawn,
                name,
                branding
            FROM trams
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &TramQuery) -> sqlx::Result<Vec<Tram>> {
        let page_length = query.page_length.unwrap_or(50).clamp(1, 1000);

        let mut builder = QueryBuilder::<Postgres>::new(
            r#"
            SELECT
                t.id,
                t.operator_id,
                t.fleet,
                t.livery_id,
                t.tram_type_id,
                t.garage,
                t.withdrawn,
                t.name,
                t.branding
            FROM trams t
            WHERE TRUE
            "#,
        );

        if let Some(value) = query.operator {
            builder.push(" AND t.operator_id = ").push_bind(value);
        }

        if let Some(value) = &query.fleet {
            builder
                .push(" AND t.fleet ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = query.livery {
            builder.push(" AND t.livery_id = ").push_bind(value);
        }

        if let Some(value) = query.tram_type {
            builder.push(" AND t.tram_type_id = ").push_bind(value);
        }

        if let Some(value) = &query.garage {
            builder
                .push(" AND t.garage ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = query.withdrawn {
            builder.push(" AND t.withdrawn = ").push_bind(value);
        }

        if let Some(value) = &query.name {
            builder
                .push(" AND t.name ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.branding {
            builder
                .push(" AND t.branding ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.search {
            let pattern = format!("%{value}%");

            builder.push(" AND (t.fleet ILIKE ");
            builder.push_bind(pattern.clone());
            builder.push(" OR t.garage ILIKE ");
            builder.push_bind(pattern.clone());
            builder.push(" OR t.name ILIKE ");
            builder.push_bind(pattern.clone());
            builder.push(" OR t.branding ILIKE ");
            builder.push_bind(pattern);
            builder.push(")");
        }

        builder
            .push(" ORDER BY t.fleet")
            .push(" LIMIT ")
            .push_bind(page_length);

        if let Some(offset) = query.offset {
            builder.push(" OFFSET ").push_bind(offset.max(0));
        }

        builder.build_query_as::<Tram>().fetch_all(&self.pool).await
    }

    pub async fn create(&self, tram: &Tram) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO trams (
                operator_id,
                fleet,
                livery_id,
                tram_type_id,
                garage,
                withdrawn,
                name,
                branding
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
            RETURNING id
            "#,
        )
        .bind(tram.operator_id)
        .bind(&tram.fleet)
        .bind(tram.livery_id)
        .bind(tram.tram_type_id)
        .bind(&tram.garage)
        .bind(tram.withdrawn)
        .bind(&tram.name)
        .bind(&tram.branding)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, tram: &Tram) -> sqlx::Result<()> {
        let result = sqlx::query(
            r#"
            UPDATE trams
            SET
                operator_id = $1,
                fleet = $2,
                livery_id = $3,
                tram_type_id = $4,
                garage = $5,
                withdrawn = $6,
                name = $7,
                branding = $8
            WHERE id = $9
            "#,
        )
        .bind(tram.operator_id)
        .bind(&tram.fleet)
        .bind(tram.livery_id)
        .bind(tram.tram_type_id)
        .bind(&tram.garage)
        .bind(tram.withdrawn)
        .bind(&tram.name)
        .bind(&tram.branding)
        .bind(tram.id)
        .execute(&self.pool)
        .await?;

        if result.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM trams WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        trams: Vec<Tram>,
        user_id: Option<i64>,
    ) -> sqlx::Result<Vec<TramFilledOut>> {
        let mut filled_out = Vec::with_capacity(trams.len());

        for tram in trams {
            let operator = match tram.operator_id {
                Some(id) => db.tram_operators.get(id).await?,
                None => None,
            };

            let tram_type = match tram.tram_type_id {
                Some(id) => db.tram_types.get(id).await?,
                None => None,
            };

            let livery = match tram.livery_id {
                Some(id) => db.tram_liveries.get(id).await?,
                None => None,
            };

            let photo = db
                .photos
                .search(&PhotoQuery {
                    id: None,
                    author_id: None,
                    photo_type: Some(PhotoType::Tram),
                    title: None,
                    description: None,
                    search: None,

                    // Bus details
                    bd_reg: None,
                    bd_fleet: None,
                    bd_livery_id: None,
                    bd_vehicle_type_id: None,
                    bd_vehicle_id: None,
                    bd_has_matched_vehicle: None,
                    bd_route: None,
                    bd_operator_id: None,

                    // Tram details
                    td_fleet: None,
                    td_livery_id: None,
                    td_vehicle_type_id: None,
                    td_operator_id: None,
                    td_vehicle_id: Some(tram.id),
                    td_has_matched_vehicle: None,

                    // Model bus details
                    mbd_manufacturer: None,
                    mbd_product_code: None,
                    mbd_scale: None,
                    mbd_operator: None,
                    mbd_livery: None,
                    mbd_fleet_number: None,
                    mbd_registration: None,
                    mbd_route_number: None,
                    mbd_destination: None,
                    mbd_vehicle_type: None,
                    mbd_has_certificate: None,
                    mbd_released: None,
                    mbd_model_id: None,
                    mbd_has_matched_model: None,
                    mbd_owner_id: user_id,

                    // Pagination
                    page_length: None,
                    offset: None,
                    order_by: None,
                })
                .await?
                .first()
                .cloned();

            let favourite = match user_id {
                Some(user_id) => {
                    db.favourites
                        .get(user_id, FavouriteType::Vehicle, tram.id)
                        .await?
                }
                None => None,
            };

            filled_out.push(TramFilledOut {
                id: tram.id,
                operator_id: tram.operator_id,
                operator,
                fleet: tram.fleet,
                livery_id: tram.livery_id,
                livery,
                tram_type_id: tram.tram_type_id,
                tram_type,
                name: tram.name,
                garage: tram.garage,
                withdrawn: tram.withdrawn,
                branding: tram.branding,
                photo,
                is_favourited: user_id.map(|_| favourite.is_some()),
            });
        }

        Ok(filled_out)
    }
}
