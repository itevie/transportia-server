use std::sync::Arc;

use sqlx::PgPool;

use crate::db::Database;
use crate::db::resource::bustimes::vehicle::BtVehicles;
use crate::db::resource::bustimes::vehicle_def::FilledOutBtVehicle;
use crate::db::resource::photo::bus_photo_details_def::{BusPhotoDetails, BusPhotoDetailsFilledOut, BusPhotoDetailsUpdate};

// TODO: Add manual operator
pub static SQL_BUS_PHOTO_DETAILS: &str = r#"
CREATE TABLE IF NOT EXISTS bus_photo_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matched_vehicle_id BIGINT REFERENCES bt_vehicles(id),
    override_match BOOLEAN NOT NULL DEFAULT FALSE,
    reg TEXT,
    fleet TEXT,
    livery_id BIGINT REFERENCES bt_liveries(id),
    vehicle_type_id BIGINT REFERENCES bt_vehicle_types(id),
    route_id TEXT REFERENCES tx_lines(tx_id)
);
"#;

#[derive(Clone)]
pub struct BusPhotoDetailsManager {
    pool: PgPool,
}

impl BusPhotoDetailsManager {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(
        &self,
        id: i64,
    ) -> sqlx::Result<Option<BusPhotoDetails>> {
        sqlx::query_as::<_, BusPhotoDetails>(
            r#"
            SELECT
                id,
                matched_vehicle_id,
                override_match,
                reg,
                fleet,
                livery_id,
                vehicle_type_id,
                route_id
            FROM bus_photo_details
            WHERE id = $1
            "#,
        )
            .bind(id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn create(
        &self,
        details: &BusPhotoDetails,
    ) -> sqlx::Result<i64> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO bus_photo_details (
                matched_vehicle_id,
                override_match,
                reg,
                fleet,
                livery_id,
                vehicle_type_id,
                route_id
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7)
            RETURNING id
            "#,
        )
            .bind(details.matched_vehicle_id)
            .bind(details.override_match)
            .bind(&details.reg)
            .bind(&details.fleet)
            .bind(details.livery_id)
            .bind(details.vehicle_type_id)
            .bind(&details.route_id)
            .fetch_one(&self.pool)
            .await
    }

    pub async fn update(
        &self,
        id: i64,
        update: &BusPhotoDetailsUpdate,
    ) -> sqlx::Result<()> {
        sqlx::query(
            r#"
            UPDATE bus_photo_details SET
                matched_vehicle_id = $1,
                override_match = $2,
                reg = $3,
                fleet = $4,
                livery_id = $5,
                vehicle_type_id = $6,
                route_id = $7
            WHERE id = $8
            "#,
        )
            .bind(update.matched_vehicle_id)
            .bind(update.override_match)
            .bind(&update.reg)
            .bind(&update.fleet)
            .bind(update.livery_id)
            .bind(update.vehicle_type_id)
            .bind(&update.route_id)
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn delete(
        &self,
        id: i64,
    ) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM bus_photo_details WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        details: BusPhotoDetails,
    ) -> sqlx::Result<BusPhotoDetailsFilledOut> {
        let livery = match details.livery_id {
            Some(id) => db.liveries.get(id).await?,
            None => None,
        };

        let vt = match details.vehicle_type_id {
            Some(id) => db.vehicle_types.get(id).await?,
            None => None,
        };

        let route = match &details.route_id {
            Some(id) => db.tx_lines.get(id).await?,
            None => None,
        };

        let matched: Option<FilledOutBtVehicle> = match details.matched_vehicle_id {
            Some(id) => {
                match db.vehicles.get(id).await? {
                    Some(vehicle) => {
                        BtVehicles::fill_out(
                            db.clone(),
                            vec![vehicle],
                            None,
                        )
                            .await?
                            .into_iter()
                            .next()
                    }
                    None => None,
                }
            }
            None => None,
        };

        Ok(BusPhotoDetailsFilledOut {
            id: details.id,
            matched_vehicle_id: details.matched_vehicle_id,
            matched_vehicle: matched,
            override_match: details.override_match,
            reg: details.reg,
            fleet: details.fleet,
            livery_id: details.livery_id,
            livery,
            vehicle_type_id: details.vehicle_type_id,
            vehicle_type: vt,
            route_id: details.route_id,
            route,
        })
    }
}