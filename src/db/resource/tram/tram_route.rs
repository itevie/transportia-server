use crate::db::resource::tram::tram_route_def::TramRoute;
use sqlx::PgPool;

pub static SQL_TRAM_ROUTE: &str = r#"
CREATE TABLE IF NOT EXISTS tram_routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    start_stop_id BIGINT NOT NULL REFERENCES tram_stops(id),
    end_stop_id BIGINT NOT NULL REFERENCES tram_stops(id),
    operator_id BIGINT NOT NULL REFERENCES tram_operators(id),
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct TramRoutes {
    pool: PgPool,
}

impl TramRoutes {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<TramRoute>> {
        sqlx::query_as::<_, TramRoute>(
            r#"
            SELECT *
            FROM tram_routes
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(&self, query: &str) -> sqlx::Result<Vec<TramRoute>> {
        let search = format!("%{}%", query);

        sqlx::query_as::<_, TramRoute>(
            r#"
            SELECT *
            FROM tram_routes
            WHERE name ILIKE $1
            ORDER BY name
            LIMIT 50
            "#,
        )
        .bind(search)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(&self, route: &TramRoute) -> sqlx::Result<i64> {
        sqlx::query_scalar(
            r#"
            INSERT INTO tram_routes (
                name,
                start_stop_id,
                end_stop_id,
                operator_id,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5)
            RETURNING id
            "#,
        )
        .bind(&route.name)
        .bind(route.start_stop_id)
        .bind(route.end_stop_id)
        .bind(route.operator_id)
        .bind(&route.created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, route: &TramRoute) -> sqlx::Result<()> {
        let result = sqlx::query(
            r#"
            UPDATE tram_routes
            SET
                name = $1,
                start_stop_id = $2,
                end_stop_id = $3,
                operator_id = $4,
                created_at = $5
            WHERE id = $6
            "#,
        )
        .bind(&route.name)
        .bind(route.start_stop_id)
        .bind(route.end_stop_id)
        .bind(route.operator_id)
        .bind(&route.created_at)
        .bind(route.id)
        .execute(&self.pool)
        .await?;

        if result.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        sqlx::query("DELETE FROM tram_routes WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}
