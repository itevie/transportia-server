use chrono::Utc;
use serde::Deserialize;
use sqlx::PgPool;
use utoipa::{IntoParams, ToSchema};
use crate::db::resource::comment::comment_def::CommentThread;

pub static SQL_COMMENT_THREAD: &str = r#"
CREATE TABLE IF NOT EXISTS comment_threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct CommentThreads {
    pool: PgPool,
}

#[derive(Deserialize, ToSchema, IntoParams)]
pub struct CommentThreadQuery {
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

impl CommentThreads {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> sqlx::Result<Option<CommentThread>> {
        sqlx::query_as::<_, CommentThread>(
            r#"
            SELECT *
            FROM comment_threads
            WHERE id = $1
            "#,
        )
            .bind(id)
            .fetch_optional(&self.pool)
            .await
    }

    pub async fn create(&self) -> sqlx::Result<i64> {
        let created_at = Utc::now().to_rfc3339();

        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO comment_threads (created_at)
            VALUES ($1)
            RETURNING id
            "#,
        )
            .bind(created_at)
            .fetch_one(&self.pool)
            .await
    }

    pub async fn search(
        &self,
        query: &CommentThreadQuery,
    ) -> sqlx::Result<Vec<CommentThread>> {
        let page_length = query.page_length.unwrap_or(50).clamp(1, 1000);
        let offset = query.offset.unwrap_or(0).max(0);

        sqlx::query_as::<_, CommentThread>(
            r#"
            SELECT *
            FROM comment_threads
            ORDER BY id DESC
            LIMIT $1 OFFSET $2
            "#,
        )
            .bind(page_length)
            .bind(offset)
            .fetch_all(&self.pool)
            .await
    }

    pub async fn delete(&self, id: i64) -> sqlx::Result<()> {
        let mut transaction = self.pool.begin().await?;

        sqlx::query("DELETE FROM comments WHERE thread = $1")
            .bind(id)
            .execute(&mut *transaction)
            .await?;

        sqlx::query("DELETE FROM comment_threads WHERE id = $1")
            .bind(id)
            .execute(&mut *transaction)
            .await?;

        transaction.commit().await?;

        Ok(())
    }
}