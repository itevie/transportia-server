use std::sync::Arc;

use serde::Deserialize;
use sqlx::{PgPool, Postgres, QueryBuilder};
use utoipa::{IntoParams, ToSchema};

use crate::db::Database;
use crate::db::resource::model_bus::model_bus::ModelBuses;
use crate::db::resource::model_bus::model_bus_ownership_def::{
    ModelBusOwnership, ModelBusOwnershipFilledOut,
};
use crate::db::resource::photo::photo::PhotoQuery;
use crate::db::resource::photo::photo_def::PhotoType;

pub static SQL_MODEL_BUS_OWNERSHIPS: &str = r#"
CREATE TABLE IF NOT EXISTS model_bus_ownerships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    model_bus_id BIGINT NOT NULL REFERENCES model_buses(id),
    certificate_number BIGINT,
    bought_at TEXT,
    defects TEXT,
    created_at TEXT NOT NULL,

    UNIQUE(model_bus_id, certificate_number)
)
"#;

#[derive(Clone)]
pub struct ModelBusOwnerships {
    pool: PgPool,
}

#[derive(Deserialize, ToSchema, IntoParams)]
pub struct ModelBusOwnershipQuery {
    pub user_id: Option<i64>,
    pub model_bus_id: Option<i64>,
    pub certificate_number: Option<i64>,
    pub bought_at: Option<String>,

    // Search
    pub search: Option<String>,

    // Model bus filters
    pub product_code: Option<String>,
    pub manufacturer: Option<String>,
    pub scale: Option<i64>,
    pub operator: Option<String>,
    pub livery: Option<String>,
    pub fleet_number: Option<String>,
    pub registration: Option<String>,
    pub route_number: Option<String>,
    pub destination: Option<String>,
    pub vehicle_type: Option<String>,
    pub has_certificate: Option<bool>,
    pub released: Option<String>,

    // Pagination
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

impl ModelBusOwnerships {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<ModelBusOwnership>, sqlx::Error> {
        sqlx::query_as::<_, ModelBusOwnership>(
            r#"
            SELECT *
            FROM model_bus_ownerships
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn search(
        &self,
        query: &ModelBusOwnershipQuery,
    ) -> Result<Vec<ModelBusOwnership>, sqlx::Error> {
        let page_length = query.page_length.unwrap_or(50).clamp(1, 1000);
        let offset = query.offset.unwrap_or(0).max(0);

        let mut builder = QueryBuilder::<Postgres>::new(
            r#"
            SELECT mbo.*
            FROM model_bus_ownerships mbo
            LEFT JOIN model_buses mb ON mb.id = mbo.model_bus_id
            WHERE TRUE
            "#,
        );

        if let Some(value) = query.user_id {
            builder.push(" AND mbo.user_id = ").push_bind(value);
        }

        if let Some(value) = query.model_bus_id {
            builder.push(" AND mbo.model_bus_id = ").push_bind(value);
        }

        if let Some(value) = query.certificate_number {
            builder
                .push(" AND mbo.certificate_number = ")
                .push_bind(value);
        }

        if let Some(value) = &query.bought_at {
            builder.push(" AND mbo.bought_at = ").push_bind(value);
        }

        // Model bus filters
        if let Some(value) = &query.product_code {
            builder
                .push(" AND mb.product_code ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.manufacturer {
            builder
                .push(" AND mb.manufacturer ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = query.scale {
            builder.push(" AND mb.scale = ").push_bind(value);
        }

        if let Some(value) = &query.operator {
            builder
                .push(" AND mb.operator ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.livery {
            builder
                .push(" AND mb.livery ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.fleet_number {
            builder
                .push(" AND mb.fleet_number ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.registration {
            builder
                .push(" AND mb.registration ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.route_number {
            builder
                .push(" AND mb.route_number ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.destination {
            builder
                .push(" AND mb.destination ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = &query.vehicle_type {
            builder
                .push(" AND mb.vehicle_type ILIKE ")
                .push_bind(format!("%{value}%"));
        }

        if let Some(value) = query.has_certificate {
            builder
                .push(" AND (mb.certificate_max > 0) = ")
                .push_bind(value);
        }

        if let Some(value) = &query.released {
            builder.push(" AND mb.released = ").push_bind(value);
        }

        // General search across ownership and model bus fields
        if let Some(value) = &query.search {
            let search = format!("%{value}%");

            builder.push(
                r#"
                AND (
                    CAST(mbo.certificate_number AS TEXT) ILIKE "#,
            );
            builder.push_bind(search.clone());

            builder.push(" OR mbo.bought_at ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.product_code ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.manufacturer ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.operator ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.livery ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.fleet_number ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.registration ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.route_number ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.destination ILIKE ");
            builder.push_bind(search.clone());

            builder.push(" OR mb.vehicle_type ILIKE ");
            builder.push_bind(search);

            builder.push(")");
        }

        builder
            .push(" ORDER BY mbo.created_at DESC")
            .push(" LIMIT ")
            .push_bind(page_length)
            .push(" OFFSET ")
            .push_bind(offset);

        builder
            .build_query_as::<ModelBusOwnership>()
            .fetch_all(&self.pool)
            .await
    }

    pub async fn create(&self, ownership: &ModelBusOwnership) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar::<_, i64>(
            r#"
            INSERT INTO model_bus_ownerships (
                user_id,
                model_bus_id,
                certificate_number,
                bought_at,
                defects,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5, $6)
            RETURNING id
            "#,
        )
        .bind(ownership.user_id)
        .bind(ownership.model_bus_id)
        .bind(ownership.certificate_number)
        .bind(&ownership.bought_at)
        .bind(&ownership.defects)
        .bind(&ownership.created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn upsert(&self, ownership: &ModelBusOwnership) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            INSERT INTO model_bus_ownerships (
                id,
                user_id,
                model_bus_id,
                certificate_number,
                bought_at,
                defects,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7)
            ON CONFLICT(id) DO UPDATE SET
                user_id = EXCLUDED.user_id,
                model_bus_id = EXCLUDED.model_bus_id,
                certificate_number = EXCLUDED.certificate_number,
                bought_at = EXCLUDED.bought_at,
                defects = EXCLUDED.defects
            "#,
        )
        .bind(ownership.id)
        .bind(ownership.user_id)
        .bind(ownership.model_bus_id)
        .bind(ownership.certificate_number)
        .bind(&ownership.bought_at)
        .bind(&ownership.defects)
        .bind(&ownership.created_at)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM model_bus_ownerships WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        ownerships: Vec<ModelBusOwnership>,
        user_id: Option<i64>,
    ) -> Result<Vec<ModelBusOwnershipFilledOut>, sqlx::Error> {
        let mut filled_out = Vec::with_capacity(ownerships.len());

        for model in ownerships {
            let model_bus = db
                .model_buses
                .get(model.model_bus_id)
                .await?
                .ok_or(sqlx::Error::RowNotFound)?;

            let mut model_bus_results =
                ModelBuses::fill_out(db.clone(), vec![model_bus], user_id).await?;

            let model_bus_f = model_bus_results.pop().ok_or(sqlx::Error::RowNotFound)?;

            let photo = db
                .photos
                .search(&PhotoQuery {
                    id: None,
                    author_id: None,
                    photo_type: Some(PhotoType::ModelBus),
                    title: None,
                    description: None,
                    search: None,
                    bd_reg: None,
                    bd_fleet: None,
                    bd_livery_id: None,
                    bd_vehicle_type_id: None,
                    bd_vehicle_id: None,
                    bd_has_matched_vehicle: None,
                    bd_route: None,
                    bd_operator_id: None,
                    td_fleet: None,
                    td_livery_id: None,
                    td_vehicle_type_id: None,
                    td_operator_id: None,
                    td_vehicle_id: None,
                    td_has_matched_vehicle: None,
                    mbd_manufacturer: None,
                    mbd_product_code: None,
                    mbd_scale: None,
                    mbd_operator: None,
                    mbd_livery: None,
                    mbd_fleet_number: None,
                    mbd_registration: None,
                    mbd_route_number: None,
                    mbd_destination: None,
                    mbd_vehicle_type: None,
                    mbd_has_certificate: None,
                    mbd_released: None,
                    mbd_model_id: Some(model.id),
                    mbd_has_matched_model: None,
                    mbd_owner_id: user_id,
                    page_length: None,
                    offset: None,
                    order_by: None,
                })
                .await?
                .into_iter()
                .next();

            filled_out.push(ModelBusOwnershipFilledOut {
                id: model.id,
                user_id: model.user_id,
                model_bus_id: model.model_bus_id,
                model_bus: model_bus_f,
                certificate_number: model.certificate_number,
                bought_at: model.bought_at,
                defects: model.defects,
                photo,
                created_at: model.created_at,
            });
        }

        Ok(filled_out)
    }
}
