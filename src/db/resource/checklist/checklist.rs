use sqlx::PgPool;

use crate::db::resource::checklist::checklist_def::{Checklist, ChecklistFilledOut};

pub static SQL_CHECKLISTS: &str = r#"
CREATE TABLE IF NOT EXISTS checklists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    checklist_type INTEGER NOT NULL,
    auto_check_photos BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct Checklists {
    pool: PgPool,
}

impl Checklists {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<Checklist>, sqlx::Error> {
        sqlx::query_as::<_, Checklist>(
            r#"
            SELECT *
            FROM checklists
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn count_items(&self, checklist_id: i64) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            SELECT COUNT(*)
            FROM checklist_items
            WHERE checklist_id = $1
            "#,
        )
        .bind(checklist_id)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn count_completed_items(&self, checklist_id: i64) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            SELECT COUNT(*)
            FROM checklist_items
            WHERE checklist_id = $1
              AND completed_at IS NOT NULL
            "#,
        )
        .bind(checklist_id)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn get_all(&self, owner_id: i64) -> Result<Vec<Checklist>, sqlx::Error> {
        sqlx::query_as::<_, Checklist>(
            r#"
            SELECT *
            FROM checklists
            WHERE owner_id = $1
            ORDER BY id
            "#,
        )
        .bind(owner_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn get_by_owner(&self, owner_id: i64) -> Result<Vec<Checklist>, sqlx::Error> {
        sqlx::query_as::<_, Checklist>(
            r#"
            SELECT *
            FROM checklists
            WHERE owner_id = $1
            ORDER BY created_at DESC
            "#,
        )
        .bind(owner_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(
        &self,
        title: &str,
        description: Option<&str>,
        owner_id: i64,
        checklist_type: i32,
        auto_check_photos: bool,
        created_at: &str,
    ) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            INSERT INTO checklists (
                title,
                description,
                owner_id,
                checklist_type,
                auto_check_photos,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5, $6)
            RETURNING id
            "#,
        )
        .bind(title)
        .bind(description)
        .bind(owner_id)
        .bind(checklist_type)
        .bind(auto_check_photos)
        .bind(created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, checklist: &Checklist) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE checklists
            SET
                title = $1,
                description = $2,
                checklist_type = $3,
                auto_check_photos = $4
            WHERE id = $5
            "#,
        )
        .bind(&checklist.title)
        .bind(&checklist.description)
        .bind(checklist.checklist_type)
        .bind(checklist.auto_check_photos)
        .bind(checklist.id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM checklists WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: std::sync::Arc<crate::db::Database>,
        checklists: Vec<Checklist>,
    ) -> Result<Vec<ChecklistFilledOut>, sqlx::Error> {
        let mut filled_out = Vec::with_capacity(checklists.len());

        for checklist in checklists {
            let count = db.checklists.count_items(checklist.id).await?;

            let completed_count = db.checklists.count_completed_items(checklist.id).await?;

            filled_out.push(ChecklistFilledOut {
                id: checklist.id,
                title: checklist.title,
                description: checklist.description,
                owner_id: checklist.owner_id,
                checklist_type: checklist.checklist_type,
                auto_check_photos: checklist.auto_check_photos,
                item_count: count,
                created_at: checklist.created_at,
                completed_item_count: completed_count,
            });
        }

        Ok(filled_out)
    }
}
