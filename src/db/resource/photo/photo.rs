/// Database representation of a photo.
///
/// `photo_type` is stored as a BIGINT in PostgreSQL, while the API model
/// uses the `PhotoType` enum.
#[derive(Debug, FromRow)]
struct PhotoRow {
    id: i64,
    author_id: i64,
    photo_type: i64,
    obj_details_id: Option<i64>,
    comment_thread: Option<i64>,
    file_name: String,
    uploaded_id: String,
    title: String,
    description: Option<String>,
    created_at: String,
    exif: Option<sqlx::types::Json<serde_json::Value>>,
}

impl TryFrom<PhotoRow> for Photo {
    type Error = sqlx::Error;

    fn try_from(row: PhotoRow) -> Result<Self, Self::Error> {
        Ok(Self {
            id: row.id,
            author_id: row.author_id,
            photo_type: photo_type_from_i64(row.photo_type)?,
            obj_details_id: row.obj_details_id,
            comment_thread: row.comment_thread,
            file_name: row.file_name,
            uploaded_id: row.uploaded_id,
            title: row.title,
            description: row.description,
            exif: row.exif,
            created_at: row.created_at,
        })
    }
}

