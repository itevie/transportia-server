use std::fs;
use std::path::Path;
use std::sync::Arc;

use chrono::Utc;
use serde::{Deserialize, Serialize};
use sqlx::{PgPool, Postgres, QueryBuilder, query_as, query_scalar};

use crate::db::Database;
use crate::db::resource::tram::tram_announcement_audio_def::TramAnnouncementAudio;

pub static SQL_TRAM_ANNOUNCEMENT_AUDIO: &str = r#"
CREATE TABLE IF NOT EXISTS tram_announcement_audios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name TEXT NOT NULL,
    audio_group TEXT NOT NULL,
    label TEXT,
    operator_id BIGINT REFERENCES tram_operators(id),
    route_id BIGINT REFERENCES tram_routes(id),
    next_stop_id BIGINT REFERENCES tram_stops(id),
    created_at TEXT NOT NULL,
    UNIQUE(file_name, audio_group)
)
"#;

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct TramAnnouncementAudioQuery {
    pub file_name: Option<String>,
    pub audio_group: Option<String>,
    pub label: Option<String>,
    pub operator: Option<i64>,
    pub route: Option<i64>,
    pub next_stop: Option<i64>,
    pub search: Option<String>,
    pub page_length: Option<i64>,
    pub offset: Option<i64>,
}

#[derive(Clone)]
pub struct TramAnnouncementAudios {
    pool: PgPool,
}

impl TramAnnouncementAudios {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<TramAnnouncementAudio>, sqlx::Error> {
        query_as::<_, TramAnnouncementAudio>(
            r#"
            SELECT *
            FROM tram_announcement_audios
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn get_groups(&self) -> Result<Vec<String>, sqlx::Error> {
        query_scalar(
            r#"
            SELECT DISTINCT audio_group
            FROM tram_announcement_audios
            ORDER BY audio_group
            "#,
        )
        .fetch_all(&self.pool)
        .await
    }

    pub async fn search(
        &self,
        query: &TramAnnouncementAudioQuery,
    ) -> Result<Vec<TramAnnouncementAudio>, sqlx::Error> {
        let page_length = query.page_length.unwrap_or(50).min(1000);

        let mut builder: QueryBuilder<Postgres> =
            QueryBuilder::new("SELECT taa.* FROM tram_announcement_audios taa WHERE 1 = 1");

        if let Some(value) = &query.file_name {
            builder
                .push(" AND taa.file_name ILIKE ")
                .push_bind(format!("%{}%", value));
        }

        if let Some(value) = &query.audio_group {
            builder
                .push(" AND taa.audio_group ILIKE ")
                .push_bind(format!("%{}%", value));
        }

        if let Some(value) = &query.label {
            builder
                .push(" AND taa.label ILIKE ")
                .push_bind(format!("%{}%", value));
        }

        if let Some(value) = query.operator {
            builder.push(" AND taa.operator_id = ").push_bind(value);
        }

        if let Some(value) = query.route {
            builder.push(" AND taa.route_id = ").push_bind(value);
        }

        if let Some(value) = query.next_stop {
            builder.push(" AND taa.next_stop_id = ").push_bind(value);
        }

        if let Some(value) = &query.search {
            let search = format!("%{}%", value);

            builder
                .push(
                    r#"
                    AND (
                        taa.file_name ILIKE "#,
                )
                .push_bind(search.clone())
                .push(" OR taa.audio_group ILIKE ")
                .push_bind(search.clone())
                .push(" OR taa.label ILIKE ")
                .push_bind(search)
                .push(")");
        }

        builder
            .push(" ORDER BY taa.audio_group, taa.file_name")
            .push(" LIMIT ")
            .push_bind(page_length);

        if let Some(offset) = query.offset {
            builder.push(" OFFSET ").push_bind(offset);
        }

        builder
            .build_query_as::<TramAnnouncementAudio>()
            .fetch_all(&self.pool)
            .await
    }

    pub async fn create(&self, audio: &TramAnnouncementAudio) -> Result<i64, sqlx::Error> {
        query_scalar(
            r#"
            INSERT INTO tram_announcement_audios (
                file_name,
                audio_group,
                label,
                operator_id,
                route_id,
                next_stop_id,
                created_at
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7)
            ON CONFLICT (file_name, audio_group)
            DO UPDATE SET file_name = EXCLUDED.file_name
            RETURNING id
            "#,
        )
        .bind(&audio.file_name)
        .bind(&audio.audio_group)
        .bind(&audio.label)
        .bind(audio.operator_id)
        .bind(audio.route_id)
        .bind(audio.next_stop_id)
        .bind(&audio.created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn scan_tram_audios<P: AsRef<Path>>(
        db: Arc<Database>,
        directory: P,
    ) -> std::io::Result<()> {
        let mut audios = Vec::new();

        for group_entry in fs::read_dir(directory)? {
            let group_entry = group_entry?;
            let group_path = group_entry.path();

            if !group_path.is_dir() {
                continue;
            }

            let audio_group = group_path
                .file_name()
                .and_then(|name| name.to_str())
                .unwrap_or_default()
                .to_string();

            for audio_entry in fs::read_dir(&group_path)? {
                let audio_entry = audio_entry?;
                let audio_path = audio_entry.path();

                if !audio_path.is_file() {
                    continue;
                }

                let file_name = audio_path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .unwrap_or_default()
                    .to_string();

                println!("Found tram announcement: {} {}", file_name, audio_group);

                audios.push(TramAnnouncementAudio {
                    id: 0,
                    file_name,
                    audio_group: audio_group.clone(),
                    label: None,
                    operator_id: None,
                    route_id: None,
                    next_stop_id: None,
                    created_at: Utc::now().to_rfc3339(),
                });
            }
        }

        for audio in audios {
            if let Err(error) = db.tram_announcement_audios.create(&audio).await {
                eprintln!("{}", error);
            }
        }

        Ok(())
    }

    pub async fn update(&self, audio: &TramAnnouncementAudio) -> Result<(), sqlx::Error> {
        let updated = sqlx::query(
            r#"
            UPDATE tram_announcement_audios
            SET
                file_name = $1,
                audio_group = $2,
                label = $3,
                operator_id = $4,
                route_id = $5,
                next_stop_id = $6,
                created_at = $7
            WHERE id = $8
            "#,
        )
        .bind(&audio.file_name)
        .bind(&audio.audio_group)
        .bind(&audio.label)
        .bind(audio.operator_id)
        .bind(audio.route_id)
        .bind(audio.next_stop_id)
        .bind(&audio.created_at)
        .bind(audio.id)
        .execute(&self.pool)
        .await?;

        if updated.rows_affected() == 0 {
            return Err(sqlx::Error::RowNotFound);
        }

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM tram_announcement_audios WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }
}
