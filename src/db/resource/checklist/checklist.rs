use sqlx::PgPool;
use std::sync::Arc;

use crate::db::Database;
use crate::db::resource::checklist::checklist_def::{RouteChecklist, RouteChecklistFilledOut};

pub static SQL_ROUTE_CHECKLISTS: &str = r#"
CREATE TABLE IF NOT EXISTS route_checklists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT NOT NULL
)
"#;

#[derive(Clone)]
pub struct RouteChecklists {
    pool: PgPool,
}

impl RouteChecklists {
    pub fn new(pool: PgPool) -> Self {
        Self { pool }
    }

    pub async fn get(&self, id: i64) -> Result<Option<RouteChecklist>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklist>(
            r#"
            SELECT *
            FROM route_checklists
            WHERE id = $1
            "#,
        )
        .bind(id)
        .fetch_optional(&self.pool)
        .await
    }

    pub async fn count_items(&self, checklist_id: i64) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            SELECT COUNT(*)
            FROM route_checklist_items
            WHERE checklist_id = $1
            "#,
        )
        .bind(checklist_id)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn count_completed_items(&self, checklist_id: i64) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            SELECT COUNT(*)
            FROM route_checklist_items
            WHERE checklist_id = $1
              AND completed_at IS NOT NULL
            "#,
        )
        .bind(checklist_id)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn get_all(&self, owner_id: i64) -> Result<Vec<RouteChecklist>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklist>(
            r#"
            SELECT *
            FROM route_checklists
            WHERE owner_id = $1
            ORDER BY id
            "#,
        )
        .bind(owner_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn get_by_owner(&self, owner_id: i64) -> Result<Vec<RouteChecklist>, sqlx::Error> {
        sqlx::query_as::<_, RouteChecklist>(
            r#"
            SELECT *
            FROM route_checklists
            WHERE owner_id = $1
            ORDER BY created_at DESC
            "#,
        )
        .bind(owner_id)
        .fetch_all(&self.pool)
        .await
    }

    pub async fn create(
        &self,
        title: &str,
        description: Option<&str>,
        owner_id: i64,
        created_at: &str,
    ) -> Result<i64, sqlx::Error> {
        sqlx::query_scalar(
            r#"
            INSERT INTO route_checklists (
                title,
                description,
                owner_id,
                created_at
            )
            VALUES ($1, $2, $3, $4)
            RETURNING id
            "#,
        )
        .bind(title)
        .bind(description)
        .bind(owner_id)
        .bind(created_at)
        .fetch_one(&self.pool)
        .await
    }

    pub async fn update(&self, checklist: &RouteChecklist) -> Result<(), sqlx::Error> {
        sqlx::query(
            r#"
            UPDATE route_checklists
            SET
                title = $1,
                description = $2
            WHERE id = $3
            "#,
        )
        .bind(&checklist.title)
        .bind(&checklist.description)
        .bind(checklist.id)
        .execute(&self.pool)
        .await?;

        Ok(())
    }

    pub async fn delete(&self, id: i64) -> Result<(), sqlx::Error> {
        sqlx::query("DELETE FROM route_checklists WHERE id = $1")
            .bind(id)
            .execute(&self.pool)
            .await?;

        Ok(())
    }

    pub async fn fill_out(
        db: Arc<Database>,
        checklists: Vec<RouteChecklist>,
    ) -> Result<Vec<RouteChecklistFilledOut>, sqlx::Error> {
        let mut filled_out = Vec::with_capacity(checklists.len());

        for checklist in checklists {
            let count = db.route_checklists.count_items(checklist.id).await?;

            let completed_count = db
                .route_checklists
                .count_completed_items(checklist.id)
                .await?;

            filled_out.push(RouteChecklistFilledOut {
                id: checklist.id,
                title: checklist.title,
                description: checklist.description,
                owner_id: checklist.owner_id,
                item_count: count,
                created_at: checklist.created_at,
                completed_item_count: completed_count,
            });
        }

        Ok(filled_out)
    }
}
